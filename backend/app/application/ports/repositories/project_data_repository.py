from typing import Protocol
from uuid import UUID


class IProjectDataRepository(Protocol):
    async def ensure_class_unused(self, project_id: UUID, class_id: UUID) -> None: ...
    async def page(self, project_id: UUID, filters: dict) -> dict: ...
    async def statistics(self, project_id: UUID) -> dict: ...
    async def cameras(self, project_id: UUID) -> list[dict]: ...
    async def link_camera(self, project_id: UUID, stream_id: UUID, linked: bool) -> None: ...
    async def mutate(self, project_id: UUID, payload: dict) -> dict: ...

